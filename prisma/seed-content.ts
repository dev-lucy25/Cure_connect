/** 앱 입력 규칙으로 검사한다. 하나라도 어긋나면 아무것도 넣지 않고 멈춘다 */
function validate() {
  for (const { id } of [...cases, ...notes]) idSchema.parse(id);
  for (const c of cases) {
    caseSchema.parse({ title: c.title, ward: c.ward, memo: c.memo });
    caseAiResultSchema.parse(c.ai);
  }
  for (const n of notes) {
    noteSchema.parse({
      hospital: n.hospital,
      ward: n.ward,
      category: n.category,
      price: String(n.price),
      title: n.title,
      questions: n.questions.join("\n"),
      supplies: n.supplies.join("\n"),
      atmosphere: n.atmosphere,
      tips: n.tips.join("\n"),
    });
  }
}

export async function seedDemoContent(db: PrismaClient, ids: { caseOwner: string; noteAuthor: string }) {
  validate();
  for (const c of cases) {
    const at = new Date(c.at);
    // AI 정리는 메모 저장 2분 뒤 → "메모가 바뀌었어요" 표시가 뜨지 않는다
    const aiAt = new Date(at.getTime() + 2 * 60_000);
    const fields = { title: c.title, ward: c.ward, memo: c.memo, memoUpdatedAt: at, aiResult: c.ai, aiAt, updatedAt: aiAt };
    await db.caseNote.upsert({ where: { id: c.id }, create: { id: c.id, userId: ids.caseOwner, createdAt: at, ...fields }, update: fields });
  }
  // 판매 수·평점은 실제 열람·평점 기록과 맞아야 해서 0으로 두고, 크레딧 보상도 주지 않는다
  for (const { id, at, ...n } of notes) {
    const createdAt = new Date(at);
    await db.wardNote.upsert({
      where: { id },
      create: { id, authorId: ids.noteAuthor, createdAt, updatedAt: createdAt, ...n },
      update: { ...n, updatedAt: createdAt },
    });
  }
  console.log(`케이스 ${cases.length}개 · 족보 ${notes.length}개를 넣었어요`);
}
